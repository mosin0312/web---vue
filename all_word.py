# 4️⃣ 過濾：長度 > 1 且不在停用詞中 
filtered = [w for w in words if len(w) > 1 and w not in stopwords] 
# 5️⃣ 統計詞頻（全部） 
counter = Counter(filtered) 
most_common = counter.most_common() # 取得所有詞 

# 印出全部詞與次數 
for w, c in most_common: print(f"{w}: {c}") 

# ========= 6. 輸出成新的 Excel & CSV ========= 
freq_df = pd.DataFrame(most_common, columns=["word", "count"]) 
freq_df.to_csv("all_keywords_freq.csv", index=False, encoding="utf-8-sig") 
freq_df.to_excel("all_keywords_freq.xlsx", index=False) 

