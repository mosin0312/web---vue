# 讀取 Excel 檔案（請確認檔名和路徑正確） 
df = pd.read_excel("165_all_20251029_1225.xlsx")  
# 假設文字都在名為 "content" 的欄位裡 
# 把所有列的 content 合併成一大段文字 
